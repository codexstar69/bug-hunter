#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const Ajv = require('ajv');
const standaloneCode = require('ajv/dist/standalone').default;
const esbuild = require('esbuild');
const { SCHEMA_FILES, VALIDATOR_EXPORTS } = require('./schema-catalog.cjs');

const projectRoot = path.resolve(__dirname, '..');
const schemaDir = path.join(projectRoot, 'schemas');
const outputPath = path.join(__dirname, 'generated-schema-validators.cjs');

function loadSchema(artifactName) {
  const schemaPath = path.join(schemaDir, SCHEMA_FILES[artifactName]);
  return JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
}

function buildValidatorBundle() {
  const ajv = new Ajv({
    allErrors: true,
    code: {
      optimize: true,
      source: true
    },
    strict: true,
    strictRequired: false
  });
  ajv.addKeyword({ keyword: 'schemaVersion', schemaType: 'number' });
  ajv.addKeyword({ keyword: 'artifact', schemaType: 'string' });

  Object.keys(VALIDATOR_EXPORTS).map((artifactName) => {
    ajv.addSchema(loadSchema(artifactName), artifactName);
    return artifactName;
  });

  const standaloneSource = standaloneCode(ajv, Object.fromEntries(
    Object.entries(VALIDATOR_EXPORTS).map(([artifactName, exportName]) => {
      return [exportName, artifactName];
    })
  ));
  const [bundle] = esbuild.buildSync({
    bundle: true,
    format: 'cjs',
    legalComments: 'none',
    minify: true,
    platform: 'node',
    stdin: {
      contents: standaloneSource,
      resolveDir: projectRoot,
      sourcefile: 'schema-validators.cjs'
    },
    target: 'node22',
    write: false
  }).outputFiles;
  return [
    '// Generated by scripts/generate-schema-validators.cjs. Do not edit.',
    bundle.text.trim(),
    ''
  ].join('\n');
}

function main() {
  const generated = buildValidatorBundle();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
    if (current !== generated) {
      throw new Error('Generated schema validators are stale. Run: pnpm generate:schema-validators');
    }
    console.log('Generated schema validators are current.');
    return;
  }
  fs.writeFileSync(outputPath, generated, 'utf8');
  console.log(`Generated ${path.relative(projectRoot, outputPath)}`);
}

try {
  main();
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  console.error(message);
  process.exit(1);
}
